import { HEALTHY_DEVICE, REQUESTERS, SCENARIOS, seedRunbooks, BASELINES } from '../domain/catalog';
import { applyAction, processDue, type Action, type Timing } from '../domain/engine';
import { DEFAULT_POLICY, HISTORICAL_POLICY_V0 } from '../domain/policy';
import type { Actor, AppState, Category, Device, Outcome } from '../domain/types';
import { DAY, MIN, iso, ms, setDeterministicIds } from '../domain/util';

const ALEX: Actor = { name: 'Alex', role: 'AGENT' };
const MORGAN: Actor = { name: 'Morgan', role: 'ADMIN' };
const HOURS = 60 * MIN;
const DETECT: Actor = { name: 'Detection engine', role: 'SYSTEM' };

function nextDue(s: AppState): number | undefined {
  const xs: number[] = [];
  for (const e of s.executions) if (e.nextAt) xs.push(ms(e.nextAt));
  for (const j of s.jobs) if (j.status === 'PENDING') xs.push(ms(j.dueAt));
  return xs.length ? Math.min(...xs) : undefined;
}

/** Reproducible synthetic history (Spec §10), generated by driving the real domain actions on a simulated clock. */
export function buildSeed(anchorMs: number): AppState {
  setDeterministicIds(20240901);
  try {
    const historyStart = anchorMs - 91 * DAY;
    let s: AppState = {
      schemaVersion: 1, anchor: iso(anchorMs), seq: { ticket: 0, audit: 0, runbook: 8, device: 0 }, devices: {}, tickets: {}, diagnoses: [],
      runbooks: seedRunbooks(iso(historyStart)), policy: HISTORICAL_POLICY_V0,
      policyHistory: [{ policy: HISTORICAL_POLICY_V0, reason: 'Historical pilot policy v0 (synthetic): preapproval enabled for LOW-risk ≥ 97', actor: 'Morgan', role: 'ADMIN', at: iso(historyStart) }],
      approvals: [], executions: [], jobs: [], audit: [], notifications: [], settings: { role: 'AGENT' },
    };
    const run = (action: Action, at: number, actor: Actor = ALEX) => {
      const r = applyAction(s, action, at, { actor });
      if (!r.ok) throw new Error(`Seed action ${action.type} failed: ${r.error?.message}`);
      s = r.state;
      return r;
    };
    const advance = (until: number, timing: Timing, from: number) => {
      s = processDue(s, from, timing);
      for (let g = 0; g < 200; g++) {
        const n = nextDue(s);
        if (n === undefined || n > until) break;
        s = processDue(s, n, timing);
      }
    };
    const timingFor = (expectedMin: number): Timing => ({ stepMs: Math.round((expectedMin * MIN) / 4), verifyMs: Math.round((expectedMin * MIN) / 4), closeMs: 2 * MIN });
    let req = 0;
    const requester = () => REQUESTERS[req++ % REQUESTERS.length];
    const create = (at: number, cat: Category, title: string, source: 'EMPLOYEE' | 'DETECTION', outcome: Outcome = 'SUCCESS', priority: 'P2' | 'P3' | 'P4' = 'P3') => {
      const who = requester();
      const r = run({ type: 'CREATE_TICKET', input: { title, description: `${title} (synthetic historical record)`, requester: who, source, priority, category: cat, outcome, scenario: 'HISTORICAL' } }, at, source === 'DETECTION' ? DETECT : { name: who, role: 'EMPLOYEE' });
      return r.ticketId!;
    };
    const anchorNoon = new Date(anchorMs); anchorNoon.setHours(12, 0, 0, 0);
    for (let i = 90; i >= 1; i--) {
      const d = new Date(anchorNoon); d.setDate(d.getDate() - i);
      const base = d.getTime();
      // Slot 0 — auto storage under historical policy v0.
      {
        const id = create(base, 'STORAGE', 'Low disk space detected', 'DETECTION', 'SUCCESS', 'P4');
        advance(base + 2 * HOURS, timingFor(3), base + 1000);
        if (i % 23 === 5) {
          run({ type: 'REOPEN', ticketId: id, byEmployee: true, reason: 'Disk filled up again after a large sync' }, base + 2 * HOURS, ALEX);
          run({ type: 'RUN_DIAGNOSIS', ticketId: id }, base + 2 * HOURS + 10 * MIN, ALEX);
          run({ type: 'RESOLVE_MANUAL', ticketId: id, note: 'Moved large sync folder to network share with employee', evidence: 'Free disk 41 GB after relocation', verified: true }, base + 2 * HOURS + 40 * MIN, ALEX);
        }
      }
      // Slot 1 — human-approved Wi-Fi with employee consent.
      {
        const t0 = base + 25 * MIN;
        const fail = i % 15 === 7;
        const id = create(t0, 'WIFI', 'Wi-Fi drops intermittently', 'EMPLOYEE', fail ? 'VERIFY_FAIL' : 'SUCCESS', 'P2');
        run({ type: 'APPROVE', ticketId: id }, t0 + 6 * MIN, ALEX);
        run({ type: 'CONSENT', ticketId: id, grant: true }, t0 + 11 * MIN, ALEX);
        advance(t0 + 60 * MIN, timingFor(5), t0 + 11 * MIN + 1000);
        if (fail) {
          run({ type: 'ROLLBACK', ticketId: id }, t0 + 20 * MIN, ALEX);
          advance(t0 + 40 * MIN, timingFor(5), t0 + 20 * MIN + 1000);
          run({ type: 'RESOLVE_MANUAL', ticketId: id, note: 'Replaced Wi-Fi driver manually after rollback', evidence: 'Connectivity probe 3/3 after driver replacement', verified: true }, t0 + 75 * MIN, ALEX);
        }
      }
      // Slot 2 — crash handled manually.
      {
        const t0 = base + 50 * MIN;
        const id = create(t0, 'CRASH', 'Application crashes on launch', 'EMPLOYEE');
        run({ type: 'RESOLVE_MANUAL', ticketId: id, note: 'Cleared corrupted app profile and reinstalled plugin', evidence: 'App launched 5 times without fault', verified: true }, t0 + (BASELINES.CRASH.resolutionMin - 10) * MIN, ALEX);
      }
      // Slot 3 — rotating pending / closed case.
      {
        const t0 = base + 75 * MIN;
        const k = i % 4;
        if (k === 0) create(t0, 'CRASH', 'Intermittent crash in reporting tool', 'EMPLOYEE');
        else if (k === 1) create(t0, 'UNKNOWN', 'Laptop behaving strangely', 'EMPLOYEE');
        else if (k === 2) create(t0, 'APP_UPDATE', 'Productivity app update required', 'DETECTION', 'SUCCESS', 'P4');
        else {
          const id = create(t0, 'SERVICE', 'Background sync service stopped', 'DETECTION');
          run({ type: 'APPROVE', ticketId: id }, t0 + 5 * MIN, ALEX);
          advance(t0 + 60 * MIN, timingFor(4), t0 + 5 * MIN + 1000);
        }
      }
    }
    // Current default policy v1 (explicit approval) — pending historical plans re-evaluated.
    const { version: _v, ...v1 } = DEFAULT_POLICY; void _v;
    run({ type: 'SAVE_POLICY', policy: v1, reason: 'Default policy v1: explicit per-ticket approval; preapproval off' }, anchorMs - 60 * MIN, MORGAN);
    // Demo fleet devices for gate demonstrations.
    const fleet: Device[] = [
      { ...HEALTHY_DEVICE, id: 'dev-mac-0042', name: 'LT-MAC-0042 (demo fleet)', os: 'macOS', osVersion: '14.6', freeGB: 4 },
      { ...HEALTHY_DEVICE, id: 'dev-crit-0007', name: 'LT-CRIT-0007 (demo fleet)', group: 'Critical', dnsHealthy: false },
      { ...HEALTHY_DEVICE, id: 'dev-unm-0013', name: 'LT-UNM-0013 (demo fleet)', managed: false, freeGB: 5 },
    ];
    s = { ...s, devices: { ...s.devices, ...Object.fromEntries(fleet.map((f) => [f.id, f])) } };
    // Today's featured demo scenarios.
    SCENARIOS.forEach((sc, idx) => {
      run({ type: 'CREATE_TICKET', input: { title: sc.title, description: sc.description, requester: REQUESTERS[idx], source: sc.source, priority: sc.priority, category: sc.category, outcome: sc.outcome, newDevice: sc.device, scenario: sc.key, demo: true } }, anchorMs - (SCENARIOS.length - idx) * 4 * MIN, sc.source === 'DETECTION' ? DETECT : { name: REQUESTERS[idx], role: 'EMPLOYEE' });
    });
    // Keep only the last 7 days of simulated in-app notifications to bound storage size.
    return { ...s, notifications: s.notifications.filter((n) => ms(n.at) >= anchorMs - 7 * DAY).map((n) => (ms(n.at) < anchorMs - DAY ? { ...n, read: true } : n)) };
  } finally {
    setDeterministicIds(null);
  }
}
