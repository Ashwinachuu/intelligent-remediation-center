import { DEFAULT_ASSUMPTIONS, HEALTHY_DEVICE, REQUESTERS, SCENARIOS, seedRunbooks } from '../domain/catalog';
import { applyAction, processDue, type Action, type Timing } from '../domain/engine';
import { DEFAULT_POLICY, HISTORICAL_POLICY_V0 } from '../domain/policy';
import type { Actor, AppState, Category, Device, Outcome } from '../domain/types';
import { DAY, MIN, iso, ms, setDeterministicIds } from '../domain/util';

const ALEX: Actor = { name: 'Alex', role: 'AGENT' };
const MORGAN: Actor = { name: 'Morgan', role: 'ADMIN' };
const DETECT: Actor = { name: 'Detection engine', role: 'SYSTEM' };

function nextDue(s: AppState): number | undefined {
  const xs: number[] = [];
  for (const e of s.executions) if (e.nextAt) xs.push(ms(e.nextAt));
  for (const j of s.jobs) if (j.status === 'PENDING') xs.push(ms(j.dueAt));
  return xs.length ? Math.min(...xs) : undefined;
}

/**
 * Small, curated synthetic history: one ticket per path (happy and unhappy) over the last 6 days,
 * generated by driving the real domain actions on a simulated clock so every record is coherent.
 * Deliberately small so every dashboard number can be explained in a demo (see domain/examples.ts).
 */
export function buildSeed(anchorMs: number): AppState {
  setDeterministicIds(20240901);
  try {
    const historyStart = anchorMs - 8 * DAY;
    let s: AppState = {
      schemaVersion: 3, anchor: iso(anchorMs), seq: { ticket: 0, audit: 0, runbook: 8, device: 0 }, devices: {}, tickets: {}, diagnoses: [],
      runbooks: seedRunbooks(iso(historyStart)), policy: HISTORICAL_POLICY_V0,
      policyHistory: [{ policy: HISTORICAL_POLICY_V0, reason: 'Pilot policy v0 (synthetic): preapproval on for LOW-risk runbooks at maturity L3/L4', actor: 'Morgan', role: 'ADMIN', at: iso(historyStart) }],
      approvals: [], executions: [], jobs: [], audit: [], notifications: [], stepApprovals: [], settings: { role: 'AGENT', assumptions: DEFAULT_ASSUMPTIONS },
    };
    const run = (action: Action, at: number, actor: Actor = ALEX) => {
      const r = applyAction(s, action, at, { actor });
      if (!r.ok) throw new Error(`Seed action ${action.type} failed: ${r.error?.message}`);
      s = r.state;
      return r;
    };
    const advance = (until: number, timing: Timing, from: number) => {
      s = processDue(s, from, timing);
      for (let g = 0; g < 200; g++) {
        const n = nextDue(s);
        if (n === undefined || n > until) break;
        s = processDue(s, n, timing);
      }
    };
    const timingFor = (expectedMin: number): Timing => ({ stepMs: Math.round((expectedMin * MIN) / 4), verifyMs: Math.round((expectedMin * MIN) / 4), closeMs: 2 * MIN });
    let req = 0;
    const requester = () => REQUESTERS[req++ % REQUESTERS.length];
    const anchorNoon = new Date(anchorMs); anchorNoon.setHours(12, 0, 0, 0);
    const day = (k: number) => { const d = new Date(anchorNoon); d.setDate(d.getDate() - k); return d.getTime(); };
    /** Create one curated example ticket (see domain/examples.ts). */
    const create = (example: string, at: number, cat: Category, title: string, o: { source?: 'EMPLOYEE' | 'DETECTION'; outcome?: Outcome; priority?: 'P2' | 'P3' | 'P4'; device?: Partial<Device> } = {}) => {
      const who = requester();
      const source = o.source ?? 'EMPLOYEE';
      const r = run({ type: 'CREATE_TICKET', input: { title, description: `${title} (curated example: ${example})`, requester: who, source, priority: o.priority ?? 'P3', category: cat, outcome: o.outcome ?? 'SUCCESS', scenario: 'HISTORICAL', example, newDevice: o.device } }, at, source === 'DETECTION' ? DETECT : { name: who, role: 'EMPLOYEE' });
      return r.ticketId!;
    };
    const manual = (id: string, at: number, note: string, evidence: string) => run({ type: 'RESOLVE_MANUAL', ticketId: id, note, evidence, verified: true }, at, ALEX);
    const T = (min: number) => min * MIN;

    // ---- 6 days ago: the three happy paths ----
    { const b = day(6);
      create('auto-fix', b, 'STORAGE', 'Low disk space detected', { source: 'DETECTION', priority: 'P4' });
      advance(b + T(60), timingFor(3), b + 1000);
      const dns = create('approved-fix', b + T(30), 'DNS', 'Internal sites not resolving');
      run({ type: 'APPROVE', ticketId: dns }, b + T(34), ALEX);
      advance(b + T(60), timingFor(2), b + T(34) + 1000);
      const svc = create('service-fix', b + T(60), 'SERVICE', 'Background sync service stopped', { source: 'DETECTION' });
      run({ type: 'APPROVE', ticketId: svc }, b + T(65), ALEX);
      advance(b + T(90), timingFor(4), b + T(65) + 1000); }
    // ---- 5 days ago: disruptive fix with consent; verification failure → rollback ----
    { const b = day(5);
      const w = create('consent-fix', b, 'WIFI', 'Wi-Fi drops intermittently', { priority: 'P2' });
      run({ type: 'APPROVE', ticketId: w }, b + T(5), ALEX);
      run({ type: 'CONSENT', ticketId: w, grant: true }, b + T(9), ALEX);
      advance(b + T(40), timingFor(5), b + T(9) + 1000);
      const f = create('verify-fail-rollback', b + T(60), 'WIFI', 'Wi-Fi unstable after dock change', { priority: 'P2', outcome: 'VERIFY_FAIL' });
      run({ type: 'APPROVE', ticketId: f }, b + T(64), ALEX);
      run({ type: 'CONSENT', ticketId: f, grant: true }, b + T(68), ALEX);
      advance(b + T(78), timingFor(5), b + T(68) + 1000);
      run({ type: 'ROLLBACK', ticketId: f }, b + T(80), ALEX);
      advance(b + T(95), timingFor(5), b + T(80) + 1000);
      manual(f, b + T(140), 'Replaced Wi-Fi driver manually after rollback', 'Connectivity probe 3/3 after driver replacement'); }
    // ---- 4 days ago: rollback failure; failure before any change; another supervised service fix ----
    { const b = day(4);
      const a = create('rollback-fail', b, 'APP_UPDATE', 'Productivity app update required', { source: 'DETECTION', priority: 'P4', outcome: 'ROLLBACK_FAIL' });
      run({ type: 'APPROVE', ticketId: a }, b + T(5), ALEX);
      run({ type: 'CONSENT', ticketId: a, grant: true }, b + T(10), ALEX);
      advance(b + T(30), timingFor(12), b + T(10) + 1000);
      run({ type: 'ROLLBACK', ticketId: a }, b + T(35), ALEX);
      advance(b + T(55), timingFor(12), b + T(35) + 1000);
      manual(a, b + T(120), 'Restored app version 2.0 manually from the software portal', 'App launches; version 2.0 confirmed');
      const x = create('exec-fail', b + T(60), 'STORAGE', 'Low disk space detected', { source: 'DETECTION', priority: 'P4', outcome: 'EXEC_FAIL' });
      advance(b + T(90), timingFor(3), b + T(60) + 1000);
      manual(x, b + T(150), 'Cleared temp files with the employee', 'Free disk 14 GB');
      const svc = create('service-fix', b + T(90), 'SERVICE', 'Background sync service stopped', { source: 'DETECTION' });
      run({ type: 'APPROVE', ticketId: svc }, b + T(95), ALEX);
      advance(b + T(120), timingFor(4), b + T(95) + 1000); }
    // ---- 3 days ago: manual fix becomes a draft runbook; employee declines ----
    { const b = day(3);
      const c = create('manual-new-runbook', b, 'CRASH', 'Design tool crashes on export');
      manual(c, b + T(150), 'Cleared corrupted export plugin cache and reinstalled plugin', 'Exported 5 files without a crash');
      run({ type: 'PROPOSE_DRAFT', fromTicketId: c }, b + T(155), ALEX);
      const r = create('consent-declined', b + T(60), 'RESTART', 'Pending restart blocking updates');
      run({ type: 'APPROVE', ticketId: r }, b + T(64), ALEX);
      run({ type: 'EMPLOYEE_RESPOND', ticketId: r, choice: 'DECLINE', note: 'In customer calls all day' }, b + T(70), ALEX);
      manual(r, b + T(300), 'Restarted together with the employee after their calls', 'Restart pending flag cleared'); }
    // ---- 2 days ago: fixed then reopened; plan rejected; unsupported device ----
    { const b = day(2);
      const st = create('reopened', b, 'STORAGE', 'Low disk space detected', { source: 'DETECTION', priority: 'P4' });
      advance(b + T(60), timingFor(3), b + 1000);
      run({ type: 'REOPEN', ticketId: st, byEmployee: true, reason: 'Disk filled up again after a large sync' }, b + T(120), ALEX);
      run({ type: 'RUN_DIAGNOSIS', ticketId: st }, b + T(130), ALEX);
      manual(st, b + T(160), 'Moved the large sync folder to a network share with the employee', 'Free disk 41 GB after relocation');
      const ap = create('rejected', b + T(60), 'APP_UPDATE', 'Productivity app update required', { source: 'DETECTION', priority: 'P4' });
      run({ type: 'REJECT', ticketId: ap, reason: 'Release freeze this week — update after Friday' }, b + T(70), ALEX);
      manual(ap, b + T(400), 'Installed 2.1 in the post-freeze maintenance window', 'App version 2.1, health check passing');
      const mac = create('unsupported-os', b + T(90), 'STORAGE', 'Mac almost out of disk space', { device: { os: 'macOS', osVersion: '14.6' } });
      manual(mac, b + T(160), 'Cleared caches manually on macOS with the employee', 'Free disk 22 GB'); }
    // ---- yesterday: approval expires; three items still needing a human ----
    { const b = day(1);
      const sv = create('approval-expired', b, 'SERVICE', 'Background sync service stopped', { source: 'DETECTION' });
      run({ type: 'SET_DEVICE', ticketId: sv, busy: true }, b + T(2), ALEX);
      run({ type: 'APPROVE', ticketId: sv }, b + T(5), ALEX);
      advance(b + T(70), timingFor(4), b + T(66));
      run({ type: 'SET_DEVICE', ticketId: sv, busy: false }, b + T(75), ALEX);
      run({ type: 'APPROVE', ticketId: sv }, b + T(80), ALEX);
      advance(b + T(110), timingFor(4), b + T(80) + 1000);
      create('unknown-open', b + T(60), 'UNKNOWN', 'Laptop making clicking noise');
      create('low-confidence', b + T(90), 'STORAGE', 'Says disk is full but cannot save files', { device: { freeGB: 40 } });
      create('critical-blocked', b + T(120), 'DNS', 'Trading desk laptop cannot resolve hosts', { priority: 'P2', device: { group: 'Critical' } }); }
    // Current default policy v1 (explicit approval) — pending historical plans re-evaluated.
    const { version: _v, ...v1 } = DEFAULT_POLICY; void _v;
    run({ type: 'SAVE_POLICY', policy: v1, reason: 'Default policy v1: explicit per-ticket approval; preapproval off' }, anchorMs - 60 * MIN, MORGAN);
    // Demo fleet devices for gate demonstrations.
    const fleet: Device[] = [
      { ...HEALTHY_DEVICE, id: 'dev-mac-0042', name: 'LT-MAC-0042 (demo fleet)', os: 'macOS', osVersion: '14.6', freeGB: 4 },
      { ...HEALTHY_DEVICE, id: 'dev-crit-0007', name: 'LT-CRIT-0007 (demo fleet)', group: 'Critical', dnsHealthy: false },
      { ...HEALTHY_DEVICE, id: 'dev-unm-0013', name: 'LT-UNM-0013 (demo fleet)', managed: false, freeGB: 5 },
    ];
    s = { ...s, devices: { ...s.devices, ...Object.fromEntries(fleet.map((f) => [f.id, f])) } };
    // Today's featured demo scenarios A–H (Spec §10), created 60–28 minutes before now.
    const AH = SCENARIOS.filter((sc) => sc.key <= 'H');
    AH.forEach((sc, idx) => {
      run({ type: 'CREATE_TICKET', input: { title: sc.title, description: sc.description, requester: REQUESTERS[idx], source: sc.source, priority: sc.priority, category: sc.category, outcome: sc.outcome, newDevice: sc.device, scenario: sc.key, demo: true } }, anchorMs - (60 - idx * 4) * MIN, sc.source === 'DETECTION' ? DETECT : { name: REQUESTERS[idx], role: 'EMPLOYEE' });
    });
    // Enhancement scenario I: multi-step OS patch, approved + consented, paused at the HIGH-risk install step.
    {
      const sc = SCENARIOS.find((x) => x.key === 'I')!;
      const t0 = anchorMs - 25 * MIN;
      const id = run({ type: 'CREATE_TICKET', input: { title: sc.title, description: sc.description, requester: REQUESTERS[8], source: sc.source, priority: sc.priority, category: sc.category, outcome: sc.outcome, newDevice: sc.device, scenario: 'I', demo: true } }, t0, DETECT).ticketId!;
      run({ type: 'APPROVE', ticketId: id, scheduleAt: iso(t0 + 3 * MIN), impactConfirmed: true }, t0 + MIN, MORGAN);
      run({ type: 'CONSENT', ticketId: id, grant: true }, t0 + 2 * MIN, { name: REQUESTERS[8], role: 'EMPLOYEE' });
      advance(t0 + 6 * MIN, { stepMs: 700, verifyMs: 900, closeMs: 700 }, t0 + 3 * MIN);
    }
    // Enhancement scenario J: three employees on the same office network report Wi-Fi drops within minutes.
    [0, 1, 2].forEach((k) => {
      const sc = SCENARIOS.find((x) => x.key === 'J')!;
      const who = REQUESTERS[10 + k];
      run({ type: 'CREATE_TICKET', input: { title: sc.title, description: sc.description, requester: who, source: 'EMPLOYEE', priority: sc.priority, category: sc.category, outcome: 'SUCCESS', newDevice: sc.device, scenario: 'J', demo: true } }, anchorMs - (18 - k * 4) * MIN, { name: who, role: 'EMPLOYEE' });
    });
    // Keep only the last 7 days of simulated in-app notifications to bound storage size.
    return { ...s, notifications: s.notifications.filter((n) => ms(n.at) >= anchorMs - 7 * DAY).map((n) => (ms(n.at) < anchorMs - DAY ? { ...n, read: true } : n)) };
  } finally {
    setDeterministicIds(null);
  }
}
